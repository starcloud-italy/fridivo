export function detectBrowserLanguage(languages = []) {
  const preferred = Array.from(languages || []).find(Boolean) || "";
  return String(preferred).toLowerCase().startsWith("it") ? "it" : "en";
}

export function resolveInitialLanguage(storedLanguage, languages = []) {
  return SUPPORTED_LANGUAGES.includes(storedLanguage)
    ? storedLanguage
    : detectBrowserLanguage(languages);
}

export function translate(language, key, variables = {}) {
  const template = TRANSLATIONS[language]?.[key] ?? TRANSLATIONS.en[key] ?? key;
  return Object.entries(variables).reduce(
    (message, [name, value]) => message.replaceAll(`{${name}}`, String(value)),
    template
  );
}
